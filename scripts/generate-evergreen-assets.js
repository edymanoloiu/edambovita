#!/usr/bin/env node
/**
 * Build-time: serialize published evergreen docs for Cloudflare/OpenNext runtime.
 * Worker FS cannot read content/*.md at request time, so we embed published docs
 * in a generated module (small set) and mirror markdown under public/_evergreen/.
 */

import fs from 'fs';
import path from 'path';
import matter from 'gray-matter';
import { CONTENT_TYPES } from '../lib/local-knowledge/contentTypes.js';
import { validateFrontmatter } from '../lib/local-knowledge/schema.js';

const root = process.cwd();
const publicDir = path.join(root, 'public', '_evergreen');
const indexPath = path.join(root, 'public', 'evergreen-index.json');
const generatedPath = path.join(root, 'lib', 'local-knowledge', 'evergreen.generated.js');

function listMarkdown(dir) {
	const abs = path.join(root, dir);
	if (!fs.existsSync(abs)) return [];
	return fs
		.readdirSync(abs)
		.filter((f) => f.endsWith('.md'))
		.map((f) => path.join(abs, f));
}

function loadAll() {
	const docs = [];
	const errors = [];

	for (const typeMeta of Object.values(CONTENT_TYPES)) {
		if (typeMeta.id === 'news') continue;
		const outTypeDir = path.join(publicDir, path.basename(typeMeta.dir));
		fs.mkdirSync(outTypeDir, { recursive: true });

		for (const filePath of listMarkdown(typeMeta.dir)) {
			const raw = fs.readFileSync(filePath, 'utf8');
			const { data, content } = matter(raw);
			const slug = data.slug || path.basename(filePath, '.md');
			const doc = {
				...data,
				slug,
				contentType: data.contentType || typeMeta.id,
				body: content,
				filePath: path.relative(root, filePath),
			};

			const validation = validateFrontmatter(doc);
			if (!validation.ok) {
				errors.push({ file: doc.filePath, errors: validation.errors });
				continue;
			}

			fs.copyFileSync(filePath, path.join(outTypeDir, `${slug}.md`));

			if (doc.status === 'published') {
				docs.push(doc);
			}
		}
	}

	return { docs, errors };
}

function main() {
	if (fs.existsSync(publicDir)) {
		fs.rmSync(publicDir, { recursive: true, force: true });
	}
	fs.mkdirSync(publicDir, { recursive: true });

	const { docs, errors } = loadAll();
	if (errors.length) {
		console.error('evergreen validation errors:', JSON.stringify(errors, null, 2));
		process.exit(1);
	}

	docs.sort(
		(a, b) =>
			Date.parse(b.dateModified || b.datePublished) - Date.parse(a.dateModified || a.datePublished)
	);

	const index = docs.map(({ body, filePath, ...meta }) => meta);
	fs.writeFileSync(indexPath, `${JSON.stringify(index)}\n`);

	const payload = JSON.stringify(docs, null, 2);
	fs.writeFileSync(
		generatedPath,
		`/* Auto-generated by scripts/generate-evergreen-assets.js — do not edit. */\nexport const PUBLISHED_EVERGREEN = ${payload};\nexport default PUBLISHED_EVERGREEN;\n`
	);

	console.log(`✅ Wrote ${docs.length} published evergreen docs to ${generatedPath}`);
	console.log(`✅ Wrote evergreen index to ${indexPath}`);
	console.log(`✅ Mirrored markdown under ${publicDir}`);
}

main();
